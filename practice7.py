"""
Вариант 1 (из занятия 7 – списки).
Задание 1: найти максимальный элемент и вывести массив в обратном порядке.
Задание 2: заменить все нулевые элементы на среднее арифметическое массива.
"""

print("=" * 50)
print("ЗАДАНИЕ 1")
print("=" * 50)

N = int(input("Введите количество элементов N: "))
a = []

for i in range(N):
    a.append(int(input(f"Введите элемент {i}: ")))

max_elem = max(a)

reversed_a = a[::-1]  # или можно через цикл

print("Исходный массив:", a)
print("Максимальный элемент:", max_elem)
print("Массив в обратном порядке:", reversed_a)

print("\n" + "=" * 50)
print("ЗАДАНИЕ 2")
print("=" * 50)

N2 = int(input("Введите количество элементов N (для второго задания): "))
b = []

for i in range(N2):
    b.append(float(input(f"Введите элемент {i}: ")))

sum_b = sum(b)
avg = sum_b / N2 if N2 != 0 else 0

for i in range(N2):
    if b[i] == 0:
        b[i] = avg

print("Среднее арифметическое:", avg)
print("Преобразованный массив:", b)