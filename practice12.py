"""
Занятие 12, блок А, задача 1.
Рекурсивно вычислить x^n / n!
"""

def power(x, n):
    """Рекурсивное возведение x в степень n."""
    if n == 0:
        return 1
    return x * power(x, n - 1)

def factorial(n):
    """Рекурсивное вычисление факториала n."""
    if n == 0:
        return 1
    return n * factorial(n - 1)

# Ввод данных
x = int(input("Введите x: "))
n = int(input("Введите n: "))

result = power(x, n) / factorial(n)
print(f"{x}^{n} / {n}! = {result}")

