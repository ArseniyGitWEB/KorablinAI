"""
Занятие 12, блок Б, задача 1.
Рекурсивно (без параметров и глобальных переменных) найти максимум
последовательности натуральных чисел, завершающейся нулём.
"""

def max_seq():
    """Считывает числа с клавиатуры, возвращает максимум."""
    a = int(input())
    if a == 0:
        return 0          # базовый случай – 0 меньше любого натурального
    else:
        # Рекурсивный вызов – максимум из текущего и остатка последовательности
        return max(a, max_seq())

print("Введите последовательность натуральных чисел (завершите нулём):")
m = max_seq()
print("Максимум:", m)

